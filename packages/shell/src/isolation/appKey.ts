// =============================================================================
// APP KEY — the app's host label and namespace key
// =============================================================================
//
// `appKeyOf` equals the server's `label_of` (`modules/shell/app_origin.py`):
// `a` + the first 24 characters of the lowercase, unpadded base32 of
// sha256(appId). Synchronous (the root mints realms synchronously), so the
// digest is computed here rather than through `crypto.subtle`. Both sides
// are pinned to `__fixtures__/appkey_vectors.json`.
// =============================================================================

const K = new Uint32Array([0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da, 0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070, 0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3, 0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2]);

/** SHA-256 of `bytes` (FIPS 180-4). */
function sha256(bytes: Uint8Array): Uint8Array {
	const bitLen = bytes.length * 8;
	const padded = new Uint8Array(((bytes.length + 9 + 63) >> 6) << 6);
	padded.set(bytes);
	padded[bytes.length] = 0x80;
	const view = new DataView(padded.buffer);
	view.setUint32(padded.length - 8, Math.floor(bitLen / 0x100000000));
	view.setUint32(padded.length - 4, bitLen >>> 0);
	const h = new Uint32Array([0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19]);
	const w = new Uint32Array(64);
	const rotr = (x: number, n: number): number => (x >>> n) | (x << (32 - n));
	for (let off = 0; off < padded.length; off += 64) {
		for (let i = 0; i < 16; i++) w[i] = view.getUint32(off + i * 4);
		for (let i = 16; i < 64; i++) {
			const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
			const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
			w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
		}
		let [a, b, c, d, e, f, g, hh] = h;
		for (let i = 0; i < 64; i++) {
			const t1 = (hh + (rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25)) + ((e & f) ^ (~e & g)) + K[i] + w[i]) >>> 0;
			const t2 = ((rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22)) + ((a & b) ^ (a & c) ^ (b & c))) >>> 0;
			hh = g;
			g = f;
			f = e;
			e = (d + t1) >>> 0;
			d = c;
			c = b;
			b = a;
			a = (t1 + t2) >>> 0;
		}
		h[0] += a;
		h[1] += b;
		h[2] += c;
		h[3] += d;
		h[4] += e;
		h[5] += f;
		h[6] += g;
		h[7] += hh;
	}
	const out = new Uint8Array(32);
	const outView = new DataView(out.buffer);
	for (let i = 0; i < 8; i++) outView.setUint32(i * 4, h[i]);
	return out;
}

const BASE32 = 'abcdefghijklmnopqrstuvwxyz234567';

/** Lowercase, unpadded RFC 4648 base32. */
function base32(bytes: Uint8Array): string {
	let bits = 0;
	let value = 0;
	let out = '';
	for (const byte of bytes) {
		value = ((value << 8) | byte) & 0xffff;
		bits += 8;
		while (bits >= 5) {
			out += BASE32[(value >>> (bits - 5)) & 31];
			bits -= 5;
		}
	}
	if (bits > 0) out += BASE32[(value << (5 - bits)) & 31];
	return out;
}

/** `is_canonical_app_id` (`modules/shell/app_origin.py`): ASCII segments joined by dots, at most 128 characters. */
const CANONICAL_APP_ID = /^[A-Za-z0-9_][A-Za-z0-9_-]*(?:\.[A-Za-z0-9_][A-Za-z0-9_-]*)*$/;

/** Whether `appId` is in canonical form (as the server requires while isolation is on). */
export function isCanonicalAppId(appId: unknown): appId is string {
	return typeof appId === 'string' && appId.length <= 128 && CANONICAL_APP_ID.test(appId);
}

/**
 * The app's host label and namespace key (`label_of`, `modules/shell/app_origin.py`).
 *
 * @param appId - A canonical app id (anything else throws: the key must never be computed from an id the server would refuse).
 * @returns `a` + 24 characters of `[a-z2-7]`.
 */
export function appKeyOf(appId: string): string {
	if (!isCanonicalAppId(appId)) throw new Error('appKeyOf: not a canonical app id');
	return `a${base32(sha256(new TextEncoder().encode(appId))).slice(0, 24)}`;
}

/**
 * The app's origin from `RR_APP_ORIGIN_TEMPLATE`.
 *
 * @param template - e.g. `https://{label}.apps.example.com`.
 * @param appId - The app id.
 * @returns The origin.
 */
export function originOf(template: string, appId: string): string {
	return new URL(template.replace('{label}', appKeyOf(appId))).origin;
}
