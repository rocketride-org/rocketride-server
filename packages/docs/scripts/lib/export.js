/**
 * docs:export — copy docs-owned readme/agent sources out to the package
 * destinations that consume them (npm/PyPI README rendering, the RocketRide
 * skill's `.rocketride/docs` reference). docs/ is the single source of truth;
 * every dest below is a generated mirror and carries the header so an editor
 * opening the package copy knows to edit upstream instead.
 *
 * `docs:check` runs the same computation with `check: true` to catch a dest
 * that was hand-edited or never exported, without writing anything.
 */

const path = require('path');
const { exists, readFile, writeFileEnsure, rm, readDir } = require('../../../../scripts/lib');

const HEADER = (src) => `<!-- GENERATED by \`./builder docs:export\` — DO NOT EDIT. Source: ${src} -->\n\n`;

const FILE_EXPORTS = [
	{ source: 'docs/clients/typescript/readme.md', dest: 'packages/client-typescript/README.md' },
	{ source: 'docs/clients/python/readme.md', dest: 'packages/client-python/README.md' },
	{ source: 'docs/mcp/readme.md', dest: 'packages/client-mcp/README.md' },
];
const DIR_EXPORTS = [
	{ source: 'docs/agents', dest: '.rocketride/docs' },
];

/**
 * Export docs-owned files to their package destinations.
 * @param {object} args
 * @param {string} args.projectRoot
 * @param {boolean} [args.check] - when true, write nothing; report drift instead.
 * @returns {Promise<{written: string[], drifted: string[]}>} repo-relative paths
 */
async function exportDocs({ projectRoot, check = false }) {
	const written = [];
	const drifted = [];

	/** Apply one source -> dest mapping: write it, or (in check mode) flag drift. */
	async function apply(destRel, expected) {
		const destAbs = path.join(projectRoot, destRel);
		const current = (await exists(destAbs)) ? await readFile(destAbs, 'utf8') : null;
		if (current === expected) return;
		if (check) {
			drifted.push(destRel);
			return;
		}
		await writeFileEnsure(destAbs, expected);
		written.push(destRel);
	}

	for (const { source, dest } of FILE_EXPORTS) {
		const content = await readFile(path.join(projectRoot, source), 'utf8');
		await apply(dest, HEADER(source) + content);
	}

	for (const { source, dest } of DIR_EXPORTS) {
		const srcDirAbs = path.join(projectRoot, source);
		const destDirAbs = path.join(projectRoot, dest);
		const srcFiles = (await exists(srcDirAbs)) ? (await readDir(srcDirAbs)).filter((f) => f.endsWith('.md')) : [];
		const srcSet = new Set(srcFiles);

		for (const filename of srcFiles) {
			const srcRel = `${source}/${filename}`;
			const destRel = `${dest}/${filename}`;
			const content = await readFile(path.join(srcDirAbs, filename), 'utf8');
			await apply(destRel, HEADER(srcRel) + content);
		}

		// Mirror deletions: a dest .md whose source no longer exists is stale.
		// Non-.md files in dest are a different concern entirely and untouched.
		const destFiles = (await exists(destDirAbs)) ? await readDir(destDirAbs) : [];
		for (const filename of destFiles) {
			if (!filename.endsWith('.md') || srcSet.has(filename)) continue;
			const destRel = `${dest}/${filename}`;
			if (check) {
				drifted.push(destRel);
				continue;
			}
			await rm(path.join(destDirAbs, filename));
		}
	}

	return { written, drifted };
}

module.exports = { exportDocs, FILE_EXPORTS, DIR_EXPORTS };
