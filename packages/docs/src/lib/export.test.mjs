import { describe, it, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtemp, rm, mkdir, writeFile, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const require = createRequire(import.meta.url);
const { exportDocs, FILE_EXPORTS, DIR_EXPORTS } = require('../../scripts/lib/export.js');

/** Build a fresh temp project root that mirrors every FILE_EXPORTS/DIR_EXPORTS source. */
async function makeProject() {
	const root = await mkdtemp(path.join(os.tmpdir(), 'rr-export-'));
	for (const { source } of FILE_EXPORTS) {
		await mkdir(path.dirname(path.join(root, source)), { recursive: true });
	}
	for (const { source } of DIR_EXPORTS) {
		await mkdir(path.join(root, source), { recursive: true });
	}
	return root;
}

describe('exportDocs — FILE_EXPORTS', () => {
	let root;

	before(async () => {
		root = await makeProject();
		for (const { source } of FILE_EXPORTS) {
			await writeFile(path.join(root, source), `# Content of ${source}\n`);
		}
	});

	after(async () => {
		await rm(root, { recursive: true, force: true });
	});

	it('writes each FILE_EXPORT dest with the generated header + source content', async () => {
		const { written } = await exportDocs({ projectRoot: root });
		for (const { source, dest } of FILE_EXPORTS) {
			assert.ok(written.includes(dest), `${dest} reported as written`);
			const out = await readFile(path.join(root, dest), 'utf8');
			assert.equal(out, `<!-- GENERATED by \`./builder docs:export\` — DO NOT EDIT. Source: ${source} -->\n\n# Content of ${source}\n`);
		}
	});
});

describe('exportDocs — check mode against a hand-edited dest', () => {
	let root;
	const target = FILE_EXPORTS[0];

	before(async () => {
		root = await makeProject();
		for (const { source } of FILE_EXPORTS) {
			await writeFile(path.join(root, source), `# Content of ${source}\n`);
		}
		await exportDocs({ projectRoot: root });
		// Hand-edit one exported dest after a clean export.
		await writeFile(path.join(root, target.dest), '# Someone edited this by hand\n');
	});

	after(async () => {
		await rm(root, { recursive: true, force: true });
	});

	it('reports the hand-edited dest as drifted and does not modify it', async () => {
		const before_ = await readFile(path.join(root, target.dest), 'utf8');
		const { drifted, written } = await exportDocs({ projectRoot: root, check: true });
		assert.ok(drifted.includes(target.dest), `${target.dest} reported as drifted`);
		assert.deepEqual(written, [], 'check mode writes nothing');
		const after_ = await readFile(path.join(root, target.dest), 'utf8');
		assert.equal(after_, before_, 'hand-edited dest left untouched');
	});
});

describe('exportDocs — DIR_EXPORTS', () => {
	let root;
	const { source: agentsSrc, dest: agentsDest } = DIR_EXPORTS[0];

	before(async () => {
		root = await makeProject();
		for (const { source } of FILE_EXPORTS) {
			await writeFile(path.join(root, source), `# Content of ${source}\n`);
		}
		await writeFile(path.join(root, agentsSrc, 'keep.md'), '# Keep me\n');
		// A dest file whose source has since been removed from docs/agents.
		await mkdir(path.join(root, agentsDest), { recursive: true });
		await writeFile(path.join(root, agentsDest, 'stale.md'), '# Stale leftover\n');
		// A non-.md dest file must survive the mirroring pass untouched.
		await writeFile(path.join(root, agentsDest, 'notes.txt'), 'plain notes\n');
	});

	after(async () => {
		await rm(root, { recursive: true, force: true });
	});

	it('copies *.md with the header and deletes a dest whose source was removed', async () => {
		await exportDocs({ projectRoot: root });
		const kept = await readFile(path.join(root, agentsDest, 'keep.md'), 'utf8');
		assert.equal(kept, `<!-- GENERATED by \`./builder docs:export\` — DO NOT EDIT. Source: ${agentsSrc}/keep.md -->\n\n# Keep me\n`);
		assert.equal(existsSync(path.join(root, agentsDest, 'stale.md')), false, 'stale dest .md removed');
		assert.equal(existsSync(path.join(root, agentsDest, 'notes.txt')), true, 'non-.md dest file left alone');
	});
});

describe('exportDocs — check mode with a missing dest', () => {
	let root;
	const target = FILE_EXPORTS[1];

	before(async () => {
		root = await makeProject();
		for (const { source } of FILE_EXPORTS) {
			await writeFile(path.join(root, source), `# Content of ${source}\n`);
		}
		// Never run exportDocs — target.dest does not exist yet.
	});

	after(async () => {
		await rm(root, { recursive: true, force: true });
	});

	it('reports a missing dest as drifted without creating it', async () => {
		const { drifted } = await exportDocs({ projectRoot: root, check: true });
		assert.ok(drifted.includes(target.dest), `${target.dest} reported as drifted`);
		assert.equal(existsSync(path.join(root, target.dest)), false, 'check mode created nothing');
	});
});
