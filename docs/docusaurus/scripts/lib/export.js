/**
 * docs:export — copy docs-owned readme sources out to the package
 * destinations that consume them (npm/PyPI README rendering). docs/ is the
 * single source of truth; every dest below is a generated mirror and
 * carries the header so an editor opening the package copy knows to edit
 * upstream instead.
 *
 * `docs:check` runs the same computation with `check: true` to catch a dest
 * that was hand-edited or never exported, without writing anything.
 *
 * Relative image links are rewritten to their raw-GitHub URL on main on the
 * way out, so the source stays previewable on any branch.
 */

const path = require('path');
const { exists, readFile, writeFileEnsure, absolutizeImageLinks } = require('../../../../scripts/lib');

const HEADER = (src) => `<!-- GENERATED by \`./builder docs:export\` — DO NOT EDIT. Source: ${src} -->\n\n`;

const FILE_EXPORTS = [
	{ source: 'docs/public/typescript/README.md', dest: 'packages/client-typescript/README.md' },
	{ source: 'docs/public/python/README.md', dest: 'packages/client-python/README.md' },
	{ source: 'docs/public/mcp/stdio/README.md', dest: 'packages/client-mcp/README.md' },
	{ source: 'docs/public/n8n/README.md', dest: 'packages/n8n-nodes/README.md' },
	{ source: 'docs/public/chat-widget/README.md', dest: 'packages/chat-widget/README.md' },
];

/**
 * Export docs-owned files to their package destinations.
 * @param {object} args
 * @param {string} args.projectRoot
 * @param {boolean} [args.check] - when true, write nothing; report drift instead.
 * @returns {Promise<{written: string[], drifted: string[]}>} repo-relative paths
 */
async function exportDocs({ projectRoot, check = false }) {
	const written = [];
	const drifted = [];

	/** Apply one source -> dest mapping: write it, or (in check mode) flag drift. */
	async function apply(destRel, expected) {
		const destAbs = path.join(projectRoot, destRel);
		const current = (await exists(destAbs)) ? await readFile(destAbs, 'utf8') : null;
		if (current === expected) return;
		if (check) {
			drifted.push(destRel);
			return;
		}
		await writeFileEnsure(destAbs, expected);
		written.push(destRel);
	}

	for (const { source, dest } of FILE_EXPORTS) {
		const content = await readFile(path.join(projectRoot, source), 'utf8');
		await apply(dest, HEADER(source) + absolutizeImageLinks(content, path.posix.dirname(source)));
	}

	return { written, drifted };
}

module.exports = { exportDocs, FILE_EXPORTS };
