/**
 * Vendored lane table for the eval scoring library.
 *
 * Source of truth: `docs/agents/ROCKETRIDE_COMPONENT_REFERENCE.md` — "Data
 * Lanes", "Control Connections", "Transformation Chains", and the
 * per-section lane notes ("Embeddings: Required Before Any Store", "Vector
 * Databases (Stores)", "The Prompt Node"). Re-vendor this file whenever that
 * doc's lane tables change.
 *
 * This is a static, hand-derived subset covering the ~25 providers the 18
 * golden briefs (`eval/src/briefs.ts`) use — NOT the full
 * `.rocketride/services-catalog.json` (that file is generated by a
 * connected server and isn't checked into this repo). Each entry lists:
 *
 *  - `accepts`: input lane names the provider's `input[].lane` may use.
 *  - `produces`: the union of output lane names the provider can emit
 *    (across all of its modes — see `LANE_DOC.md#Data Lanes` for the
 *    canonical list of lane names).
 *  - `source`: true for pipeline entry points (no `input` array).
 *  - `dualMode`: true for vector stores (`documents` in -> stored, `[]` out;
 *    `questions` in -> `[documents, answers, questions]` out).
 */

export const ALL_LANES = [
	'tags',
	'text',
	'table',
	'documents',
	'questions',
	'answers',
	'image',
	'audio',
	'video',
] as const;

export type LaneName = (typeof ALL_LANES)[number];

export interface LaneSignature {
	accepts: string[];
	produces: string[];
	source?: boolean;
	dualMode?: boolean;
}

/** Provider name -> lane signature. Family entries (e.g. `llm_*`) are matched by prefix in `laneSignatureFor`. */
export const LANE_TABLE: Record<string, LaneSignature> = {
	// Sources — classType `source`. No `input` array; produce their lane with no accepted input.
	webhook: { accepts: [], produces: ['tags'], source: true },
	dropper: { accepts: [], produces: ['tags'], source: true },
	chat: { accepts: [], produces: ['questions'], source: true },

	// Data / text chain
	parse: { accepts: ['tags'], produces: ['text', 'table', 'image', 'audio', 'video'] },
	preprocessor_langchain: { accepts: ['text'], produces: ['documents'] },
	question: { accepts: ['text'], produces: ['questions'] },
	anonymize_text: { accepts: ['text'], produces: ['text'] },
	summarization: { accepts: ['text'], produces: ['text'] }, // control: llm (required)
	extract_data: { accepts: ['text'], produces: ['answers'] }, // control: llm (required)
	ocr: { accepts: ['image'], produces: ['text', 'table'] },
	audio_transcribe: { accepts: ['audio'], produces: ['text'] },
	frame_grabber: { accepts: ['video'], produces: ['image'] },
	accessibility_describe: { accepts: ['image'], produces: ['text'] },

	// Prompt: collects documents/text/table silently, `questions` triggers the merge
	prompt: { accepts: ['documents', 'text', 'table', 'questions'], produces: ['questions'] },

	// Embeddings — documents in -> documents (with vectors); questions in -> questions (with vectors)
	embedding_transformer: { accepts: ['documents', 'questions'], produces: ['documents', 'questions'] },
	embedding_openai: { accepts: ['documents', 'questions'], produces: ['documents', 'questions'] },
	embedding_image: { accepts: ['image', 'documents'], produces: ['documents'] },

	// Vector stores — dual mode (store: documents -> []; search: questions -> documents/answers/questions)
	qdrant: { accepts: ['documents', 'questions'], produces: ['documents', 'answers', 'questions'], dualMode: true },
	chroma: { accepts: ['documents', 'questions'], produces: ['documents', 'answers', 'questions'], dualMode: true },
	pinecone: { accepts: ['documents', 'questions'], produces: ['documents', 'answers', 'questions'], dualMode: true },
	weaviate: { accepts: ['documents', 'questions'], produces: ['documents', 'answers', 'questions'], dualMode: true },
	milvus: { accepts: ['documents', 'questions'], produces: ['documents', 'answers', 'questions'], dualMode: true },

	// LLM family (llm_openai, llm_anthropic, llm_gemini, llm_mistral, llm_qwen, llm_ollama, ...)
	'llm_*': { accepts: ['questions'], produces: ['answers'] },

	// Agents — data-fed by `questions`, produce `answers`. Their LLM/tool/memory deps are control-plane, not lanes.
	agent_rocketride: { accepts: ['questions'], produces: ['answers'] },
	agent_crewai: { accepts: ['questions'], produces: ['answers'] },
	agent_langchain: { accepts: ['questions'], produces: ['answers'] },

	// Database (agent-controlled, `invoke`-driven — no direct data lanes of its own)
	db_postgres: { accepts: [], produces: [] },
	db_mysql: { accepts: [], produces: [] },

	// Tools + memory — classType `tool`/`memory`. Empty lanes: invoked via `control`, not wired via `input`.
	tool_http_request: { accepts: [], produces: [] },
	tool_python: { accepts: [], produces: [] },
	tool_chartjs: { accepts: [], produces: [] },
	memory_internal: { accepts: [], produces: [] },

	// Response / infrastructure — terminal, empty output.
	response_text: { accepts: ['text'], produces: [] },
	response_answers: { accepts: ['answers'], produces: [] },
	response_documents: { accepts: ['documents'], produces: [] },
};

/** Resolves a provider name to its lane signature, matching `llm_*` family entries by prefix. */
export function laneSignatureFor(provider: string): LaneSignature | undefined {
	if (LANE_TABLE[provider]) return LANE_TABLE[provider];
	if (provider.startsWith('llm_')) return LANE_TABLE['llm_*'];
	return undefined;
}
